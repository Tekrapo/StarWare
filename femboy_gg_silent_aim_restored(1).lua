    local function readPlayerData(data)
        if typeof(data) ~= "table" then return end
        for key, entry in pairs(data) do
            local player = typeof(key) == "Instance" and key or Players:FindFirstChild(tostring(key))
            if player and typeof(entry) == "table" then
                local role = entry.Role or entry.role
                if role then RoleByPlayer[player] = tostring(role) end
                DeadByPlayer[player] = (entry.Dead == true or entry.Killed == true) or nil
            end
        end
    end

    local function bindPlayerData()
        for _, remote in ipairs(ReplicatedStorage:GetDescendants()) do
            pcall(function()
                if remote:IsA("RemoteEvent") and remote.Name == "PlayerDataChanged" then
                    remote.OnClientEvent:Connect(function(data) pcall(readPlayerData, data) end)
                elseif remote:IsA("RemoteEvent") and remote.Name == "LoadingMap" then
                    remote.OnClientEvent:Connect(function()
                        table.clear(RoleByPlayer)
                        table.clear(DeadByPlayer)
                    end)
                elseif remote:IsA("RemoteFunction") and remote.Name == "GetPlayerData" then
                    task.spawn(function()
                        local ok, data = pcall(function() return remote:InvokeServer() end)
                        if ok then readPlayerData(data) end
                    end)
                end
            end)
        end
    end
    pcall(bindPlayerData)

    local function isHostileRole(role)
        if type(role) ~= "string" then return false end
        local lower = string.lower(role)
        return lower == "murderer" or lower:find("zomb", 1, true) ~= nil or lower:find("infect", 1, true) ~= nil
    end

    local function playerIsEnemy(player)
        if player == LocalPlayer or DeadByPlayer[player] then return false end
        if isHostileRole(RoleByPlayer[player]) then return true end
        local character = player.Character
        if character then
            if character:FindFirstChild("Knife") then return true end
            local role = player:GetAttribute("Role") or player:GetAttribute("Team")
                or character:GetAttribute("Role") or character:GetAttribute("Team")
            if isHostileRole(role) then return true end
        end
        return player.Team ~= nil and isHostileRole(player.Team.Name)
    end

    local function getAimPart(character)
        local wanted = SilentAimState.Part or "Head"
        local part = character and character:FindFirstChild(wanted)
        if part and part:IsA("BasePart") then return part end
        if wanted == "UpperTorso" then part = character and character:FindFirstChild("Torso") end
        if wanted == "Torso" then part = character and character:FindFirstChild("UpperTorso") end
        if part and part:IsA("BasePart") then return part end
        return character and (character:FindFirstChild("HumanoidRootPart") or character:FindFirstChild("Head"))
    end

    function ST.velOf(targetPart)
        local record = History[targetPart]
        local velocity = targetPart.AssemblyLinearVelocity
        local horizontal = Vector3.new(velocity.X, 0, velocity.Z)
        local historical = record and Vector3.new(record.Velocity.X, 0, record.Velocity.Z) or Vector3.zero
        if horizontal.Magnitude < 1 and historical.Magnitude > 4 then horizontal = historical end
        return horizontal, velocity.Y
    end

    function ST.farmerLike(targetPart)
        local params = RaycastParams.new()
        params.FilterType = Enum.RaycastFilterType.Exclude
        params.FilterDescendantsInstances = { targetPart.Parent, LocalPlayer.Character }
        local down = workspace:Raycast(targetPart.Position, Vector3.new(0, -12, 0), params)
        local up = workspace:Raycast(targetPart.Position, Vector3.new(0, 30, 0), params)
        return (not down) or (up and not down)
    end

    local function predict(targetPart, multiplier, extra)
        local velocity, verticalVelocity = ST.velOf(targetPart)
        local lead = (math.clamp(ping or 0.08, 0, 0.6) + 0.1) * (multiplier or 1) + (extra or 0)
        local record = History[targetPart]
        local realVelocity = targetPart.AssemblyLinearVelocity
        if record and record.Velocity and record.Velocity.Magnitude > 32
            and realVelocity.Magnitude < 1 and ST.farmerLike(targetPart) then
            return targetPart.Position + record.Velocity * lead, Vector3.new(record.Velocity.X, 0, record.Velocity.Z)
        end
        local position = targetPart.Position + velocity * lead
        if math.abs(verticalVelocity) > 3 then
            local dy = verticalVelocity * lead - 0.5 * 196.2 * lead * lead
            position += Vector3.new(0, math.clamp(dy, -6, 6), 0)
            local floorParams = RaycastParams.new()
            floorParams.FilterType = Enum.RaycastFilterType.Exclude
            floorParams.FilterDescendantsInstances = { targetPart.Parent, LocalPlayer.Character }
            local floorHit = workspace:Raycast(targetPart.Position, Vector3.new(0, -60, 0), floorParams)
            if floorHit and position.Y < floorHit.Position.Y + 2.5 then
                position = Vector3.new(position.X, floorHit.Position.Y + 2.5, position.Z)
            end
        end
        return position, velocity
    end

    function ST.wbOrigin(aimPosition, origin, targetCharacter)
        local ignore = { targetCharacter }
        if LocalPlayer.Character then ignore[2] = LocalPlayer.Character end
        RayParams.FilterDescendantsInstances = ignore
        Overlap.FilterDescendantsInstances = ignore
        local direction = aimPosition - origin
        direction = direction.Magnitude > 0.01 and direction.Unit or Vector3.new(0, 0, -1)
        local side = Vector3.new(-direction.Z, 0, direction.X)
        side = side.Magnitude > 0.01 and side.Unit or Vector3.new(1, 0, 0)
        local up = Vector3.new(0, 1, 0)
        local offsets = { -direction, (-direction + up * 0.6).Unit, up, side, -side,
            (-direction + side).Unit, (-direction - side).Unit, (up + side).Unit, (up - side).Unit }
        for _, distance in ipairs({ 2, 3, 4.5, 6, 8 }) do
            for _, offset in ipairs(offsets) do
                local candidate = aimPosition + offset * distance
                if not workspace:Raycast(candidate, aimPosition - candidate, RayParams) then
                    local ok, parts = pcall(function() return workspace:GetPartBoundsInRadius(candidate, 0.35, Overlap) end)
                    if not ok or #parts == 0 then return candidate end
                end
            end
        end
        return aimPosition - direction * 2
    end

    function ST.findPeek(origin, aim, targetCharacter, radius)
        local character = LocalPlayer.Character
        local root = character and character:FindFirstChild("HumanoidRootPart")
        if not root then return nil end
        local ignore = { targetCharacter, character }
        RayParams.FilterDescendantsInstances = ignore
        Overlap.FilterDescendantsInstances = ignore
        local base = root.Position
        local gunOffset = origin - base
        local flat = aim - base
        flat = Vector3.new(flat.X, 0, flat.Z)
        local forward = flat.Magnitude > 0.01 and flat.Unit or Vector3.new(0, 0, -1)
        local right = Vector3.new(-forward.Z, 0, forward.X)
        local angles = { 90, -90, 65, -65, 115, -115, 40, -40, 140, -140, 15, -15, 165, -165, 0, 180 }
        local boxSize = Vector3.new(1.8, 4.4, 1.4)
        for _, height in ipairs({ 0, 2.5 }) do
            for _, distance in ipairs({ 1.5, 2.5, 3.5, 5, 7, 9.5, 12, 15, 19, 24, 30, 35, 40 }) do
                if distance <= radius then
                    for _, degrees in ipairs(angles) do
                        local radians = math.rad(degrees)
                        local direction = forward * math.cos(radians) + right * math.sin(radians)
                        local position = base + direction * distance + Vector3.new(0, height, 0)
                        local gunPosition = position + gunOffset
                        if not workspace:Raycast(gunPosition, aim - gunPosition, RayParams) then
                            local ok, parts = pcall(function()
                                return workspace:GetPartBoundsInBox(CFrame.new(position), boxSize, Overlap)
                            end)
                            if not ok or #parts == 0 then
                                return { hrp = position, gun = gunPosition, dist = distance }
                            end
                        end
                    end
                end
            end
        end
        return nil
    end

    function ST.fireShoot(remote, ...)
        if remote:IsA("RemoteFunction") then
            local args = table.pack(...)
            task.spawn(function()
                pcall(function() remote:InvokeServer(table.unpack(args, 1, args.n)) end)
            end)
        else
            remote:FireServer(...)
        end
    end

    function ST.peekShot(remote, payload)
        local character = LocalPlayer.Character
        local root = character and character:FindFirstChild("HumanoidRootPart")
        if not root or ST.peekBusy then return end
        ST.peekBusy = true
        local look = payload.args[2]
        ST.ghost = { pos = payload.hrp, face = typeof(look) == "CFrame" and look.Position or nil }
        pcall(function()
            local okPing, networkPing = pcall(function() return LocalPlayer:GetNetworkPing() end)
            local hold = math.clamp((okPing and networkPing or 0.1) * 0.6 + 0.08, 0.1, 0.3)
            local started = os.clock()
            repeat RunService.Heartbeat:Wait() until os.clock() - started >= hold
            ST.fireShoot(remote, table.unpack(payload.args, 1, payload.args.n))
            local firedAt = os.clock()
            repeat RunService.Heartbeat:Wait() until os.clock() - firedAt >= 0.06
        end)
        ST.ghost = nil
        ST.peekBusy = false
    end

    function ST.myGun()
        local character = LocalPlayer.Character
        if not character then return nil end
        for _, tool in ipairs(character:GetChildren()) do
            if tool:IsA("Tool") and tool:FindFirstChild("Shoot") then return tool end
        end
        return character:FindFirstChild("Gun")
    end

    function ST.gunAttachment(gun)
        local attachment = gun and gun:FindFirstChild("GunRaycastAttachment1", true)
        return attachment and attachment:IsA("Attachment") and attachment or nil
    end

    function ST.gunOrigin()
        local gun = ST.myGun()
        if not gun then return nil end
        local handle = gun:FindFirstChild("Handle")
        local attachment = ST.gunAttachment(gun)
        if attachment then
            if attachment.Parent and attachment.Parent:IsA("BasePart") then return attachment.WorldPosition end
            if handle then return (handle.CFrame * attachment.CFrame).Position end
        end
        return handle and handle.Position or nil
    end

    function ST.moveGunAttachment(point)
        local gun = ST.myGun()
        local attachment = ST.gunAttachment(gun)
        local handle = gun and gun:FindFirstChild("Handle")
        if not (attachment and handle) then return end
        local old = attachment.CFrame
        pcall(function()
            if attachment.Parent and attachment.Parent:IsA("BasePart") then
                attachment.WorldPosition = point
            else
                attachment.CFrame = handle.CFrame:ToObjectSpace(CFrame.new(point))
            end
        end)
        task.delay(0.25, function() pcall(function() attachment.CFrame = old end) end)
    end

    function ST.calcAll(origin, targetPart, wallbang)
        local multiplier = SilentAimState.Prediction == "None" and 0 or 1
        local aimPosition = targetPart.Position
        if multiplier > 0 then
            aimPosition = predict(targetPart, multiplier)
        end
        aimPosition += Vector3.new(0, 0.2, 0)
        ST.aimPos = aimPosition
        local toTarget = aimPosition - origin
        local direction = toTarget.Magnitude > 0.01 and toTarget.Unit or Vector3.new(0, 0, -1)
        if wallbang then
            local ignore = { targetPart.Parent }
            if LocalPlayer.Character then ignore[2] = LocalPlayer.Character end
            RayParams.FilterDescendantsInstances = ignore
            if workspace:Raycast(origin, toTarget, RayParams) then
                local peek = ST.findPeek(origin, aimPosition, targetPart.Parent, 60)
                if peek then
                    local peekDirection = aimPosition - peek.gun
                    peekDirection = peekDirection.Magnitude > 0.01 and peekDirection.Unit or direction
                    return { { peek.gun, aimPosition + peekDirection * 3, peek = peek.hrp } }
                end
                local newOrigin = ST.wbOrigin(aimPosition, origin, targetPart.Parent)
                ST.moveGunAttachment(newOrigin)
                local redirected = aimPosition - newOrigin
                redirected = redirected.Magnitude > 0.01 and redirected.Unit or direction
                return { { newOrigin, aimPosition + redirected * 3 } }
            end
        end
        return { { nil, aimPosition + direction * 2 } }
    end

    local function chooseTarget()
        local camera = workspace.CurrentCamera
        if not camera then return nil end
        local center = camera.ViewportSize * 0.5
        local bestPart, bestScore = nil, math.huge
        for _, player in ipairs(Players:GetPlayers()) do
            if playerIsEnemy(player) then
                local character = player.Character
                local humanoid = character and character:FindFirstChildOfClass("Humanoid")
                local part = character and getAimPart(character)
                if humanoid and humanoid.Health > 0 and part and part:IsA("BasePart") then
                    local screen, visible = camera:WorldToViewportPoint(part.Position)
                    if visible and screen.Z > 0 then
                        local delta = (Vector2.new(screen.X, screen.Y) - center).Magnitude
                        local angle = math.deg(math.atan(delta / math.max(camera.ViewportSize.Y * 0.5, 1)))
                        if angle <= SilentAimState.FOV and delta < bestScore then
                            bestPart, bestScore = part, delta
                        end
                    end
                end
            end
        end
        return bestPart
    end

    RunService.RenderStepped:Connect(function()
        local now = os.clock()
        for _, player in ipairs(Players:GetPlayers()) do
            local character = player.Character
            local part = character and getAimPart(character)
            if part and part:IsA("BasePart") then
                local record = History[part]
                if record then
                    local dt = now - record.Time
                    if dt > 0.0005 then
                        local velocity = (part.Position - record.Position) / dt
                        if velocity.Magnitude > 150 then velocity = Vector3.zero end
                        record.Velocity = record.Velocity:Lerp(velocity, math.min(1, dt * 14))
                        record.Position, record.Time = part.Position, now
                    end
                else
                    History[part] = { Position = part.Position, Time = now, Velocity = Vector3.zero }
                end
            end
        end
        pcall(function() ping = math.clamp(LocalPlayer:GetNetworkPing(), 0, 0.6) end)
        CurrentTarget = SilentAimState.Enabled and chooseTarget() or nil
        ST.target = CurrentTarget
    end)

    local function installShootHook()
        if game.PlaceId ~= 142823291 then
            warn("[femboy.gg] Zenith Silent Aim: MM2 place check failed; hook not installed")
            return
        end
        if type(hookmetamethod) ~= "function" or type(getnamecallmethod) ~= "function" or type(checkcaller) ~= "function" then
            warn("[femboy.gg] Zenith Silent Aim: executor namecall hook is unavailable")
            return
        end
        local wrap = type(newcclosure) == "function" and newcclosure or function(fn) return fn end
        OldNamecall = hookmetamethod(game, "__namecall", wrap(function(self, ...)
            local method = getnamecallmethod()
            local target = ST.target
            if SilentAimState.Enabled and target and target.Parent and not checkcaller()
                and typeof(self) == "Instance" and (method == "FireServer" or method == "InvokeServer")
                and self.Name == "Shoot" then
                local parent = self.Parent
                if parent and (parent.Name == "Gun" or parent:IsA("Tool"))
                    and (SilentAimState.HitChance >= 100 or math.random(1, 100) <= SilentAimState.HitChance) then
                    local args = table.pack(...)
                    local first, second
                    for index = 1, args.n do
                        if typeof(args[index]) == "CFrame" then
                            if not first then first = index else second = index; break end
                        end
                    end
                    if first then
                        local ok, redirected = pcall(function()
                            local origin = ST.gunOrigin() or args[first].Position
                            local list = ST.calcAll(origin, target, SilentAimState.Wallbang)
                            local shot = list[1]
                            args[first] = CFrame.lookAt(shot[1] or origin, shot[2])
                            if second then args[second] = CFrame.new(shot[2]) end
                            return { args = args, peek = shot.peek }
                        end)
                        if ok and redirected then
                            if redirected.peek then
                                task.spawn(ST.peekShot, self, { args = redirected.args, hrp = redirected.peek })
                                return nil
                            end
                            if type(setnamecallmethod) == "function" then pcall(setnamecallmethod, method) end
                            return OldNamecall(self, table.unpack(redirected.args, 1, redirected.args.n))
                        end
                    end
                end
            end
            return OldNamecall(self, ...)
        end))
    end

    local ok, err = pcall(installShootHook)
    if not ok then warn("[femboy.gg] Zenith Silent Aim hook failed: " .. tostring(err)) end
    Players.PlayerRemoving:Connect(function(player)
        RoleByPlayer[player], DeadByPlayer[player] = nil, nil
    end)
end

