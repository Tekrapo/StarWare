	-- ---------- logo (embedded png -> custom asset) ----------
	local function LogoAsset()
		local GetAsset = getcustomasset or getsynasset
		if not (writefile and GetAsset) then
			return nil
		end
		local Ok, Asset = pcall(function()
			local Folder = "femboy"
			if makefolder and isfolder and not isfolder(Folder) then
				pcall(makefolder, Folder)
			end
			local Path = Folder .. "/logo_v3.png"
			if not (isfile and isfile(Path)) then
				writefile(Path, DecodeBase64(LOGO_B64))
			end
			return GetAsset(Path)
		end)
		if Ok and type(Asset) == "string" and Asset ~= "" then
			return Asset
		end
		return nil
	end

	-- ---------- state helpers ----------
	-- Best-effort boolean state of a Toggle: its own .State, else what we tracked from callbacks.
	local function ToggleState(Obj, Rec)
		if type(Obj) == "table" and type(Obj.State) == "boolean" then
			return Obj.State
		end
		if Rec then
			return Rec.Tracked == true
		end
		return false
	end

	local function Flip(Rec, State)
		-- callbacks that pass no argument still tell us "it changed"
		if type(State) == "boolean" then
			Rec.Tracked = State
		else
			Rec.Tracked = not Rec.Tracked
		end
		return Rec.Tracked
	end

	-- ---------- scale ----------
	local function Viewport()
		local Camera = workspace.CurrentCamera
		local Size = Camera and Camera.ViewportSize or Vector2.new(1280, 720)
		local Inset = 0
		pcall(function()
			Inset = GuiService:GetGuiInset().Y
		end)
		return Size, Inset
	end

	function Hud.GetScale()
		if Hud.Settings.AutoScale then
			local Size, Inset = Viewport()
			local Fit = math.min((Size.X - 16) / BASE_W, (Size.Y - Inset - 16) / BASE_H)
			return math.clamp(Fit, 0.35, 1)
		end
		return math.clamp(Hud.Settings.Scale, 0.35, 1.25)
	end

	local function FindWindow()
		for _, Win in ipairs(Femboy.Windows or {}) do
			if type(Win) == "table" and typeof(Win.Canvas) == "Instance" and Win.Canvas.Parent then
				return Win.Canvas
			end
		end
		local Root = Femboy._Instance
		if typeof(Root) == "Instance" then
			local View = Viewport()
			local Best, BestArea = nil, 0
			for _, Child in ipairs(Root:GetChildren()) do
				if Child:IsA("GuiObject") then
					local Size = Child.AbsoluteSize
					local Full = Size.X >= View.X * 0.95 and Size.Y >= View.Y * 0.95
					local Area = Size.X * Size.Y
					if not Full and Area > BestArea then
						Best, BestArea = Child, Area
					end
				end
			end
			return Best
		end
		return nil
	end

	-- cached: the slider fires many times per second, so never rescan the gui tree here
	function Hud.GetCanvas()
		local Canvas = Hud.Canvas
		if Canvas and Canvas.Parent then
			return Canvas
		end
		Hud.Canvas = FindWindow()
		return Hud.Canvas
	end

	function Hud.ApplyScale()
		local Scale = Hud.GetScale()
		Hud.BaseScale = Scale

		local Canvas = Hud.GetCanvas()
		if Canvas then
			local Obj = Hud.ScaleObj
			if not (Obj and Obj.Parent == Canvas) then
				Obj = Canvas:FindFirstChildOfClass("UIScale") or New("UIScale", { Name = "FemboyScale" }, Canvas)
				Hud.ScaleObj = Obj
			end
			Obj.Scale = Scale * Hud.Pop
			Hud.HookCanvas(Canvas)
		end

		local HudScale = math.clamp(Scale, 0.65, 1)
		for _, Name in ipairs({ "Watermark", "KeybindList" }) do
			local Frame = Hud.Gui and Hud.Gui:FindFirstChild(Name)
			local Sc = Frame and Frame:FindFirstChild("HudScale")
			if Sc then
				Sc.Scale = HudScale * 0.92
			end
		end
	end

	-- coalesce bursts (slider drags) into one apply
	function Hud.RequestScale()
		if Hud.ScalePending then
			return
		end
		Hud.ScalePending = true
		task.delay(0.08, function()
			Hud.ScalePending = false
			local Ok, Err = pcall(Hud.ApplyScale)
			if not Ok then
				Warn("scale", Err)
			end
		end)
	end

	-- ---------- smooth open / close ----------
	local Fade = { Alpha = 1, Target = 1, Open = true, List = nil, Conn = nil, Internal = false }

	local function CollectFade(Root)
		local List = {}
		local function Add(Obj, Prop)
			local Ok, Value = pcall(function()
				return Obj[Prop]
			end)
			if Ok and type(Value) == "number" then
				List[#List + 1] = { Obj, Prop, Value }
			end
		end
		local function Visit(Obj)
			if Obj:IsA("GuiObject") then
				Add(Obj, "BackgroundTransparency")
				if Obj:IsA("TextLabel") or Obj:IsA("TextButton") or Obj:IsA("TextBox") then
					Add(Obj, "TextTransparency")
					Add(Obj, "TextStrokeTransparency")
				end
				if Obj:IsA("ImageLabel") or Obj:IsA("ImageButton") then
					Add(Obj, "ImageTransparency")
				end
				if Obj:IsA("ScrollingFrame") then
					Add(Obj, "ScrollBarImageTransparency")
				end
			elseif Obj:IsA("UIStroke") then
				Add(Obj, "Transparency")
			end
		end
		Visit(Root)
		for _, Descendant in ipairs(Root:GetDescendants()) do
			Visit(Descendant)
		end
		return List
	end

	local function Paint(Eased)
		local List = Fade.List
		if not List then
			return
		end
		local Inverse = 1 - Eased
		pcall(function()
			for _, Item in ipairs(List) do
				Item[1][Item[2]] = Item[3] + (1 - Item[3]) * Inverse
			end
		end)
		Hud.Pop = 0.94 + 0.06 * Eased
		local Obj = Hud.ScaleObj
		if Obj and Hud.BaseScale then
			Obj.Scale = Hud.BaseScale * Hud.Pop
		end
	end

	local function Restore()
		local List = Fade.List
		if List then
			pcall(function()
				for _, Item in ipairs(List) do
					Item[1][Item[2]] = Item[3]
				end
			end)
		end
		Fade.List = nil
		Hud.Pop = 1
		local Obj = Hud.ScaleObj
		if Obj and Hud.BaseScale then
			Obj.Scale = Hud.BaseScale
		end
	end

	local function FinishFade()
		if Fade.Conn then
			Fade.Conn:Disconnect()
			Fade.Conn = nil
		end
		Restore()
		if Fade.Target == 0 then
			local Canvas = Hud.Canvas
			if Canvas then
				Fade.Internal = true
				Canvas.Visible = false
				Fade.Internal = false
			end
		end
	end

	local function StepFade(Dt)
		local Direction = Fade.Target > Fade.Alpha and 1 or -1
		Fade.Alpha = math.clamp(Fade.Alpha + Direction * Dt / FADE_TIME, 0, 1)
		if (Direction == 1 and Fade.Alpha >= Fade.Target) or (Direction == -1 and Fade.Alpha <= Fade.Target) then
			Fade.Alpha = Fade.Target
		end
		local Eased = Fade.Alpha * Fade.Alpha * (3 - 2 * Fade.Alpha)
		Paint(Eased)
		if Fade.Alpha == Fade.Target then
			FinishFade()
		end
	end

	local function RunFade(Target)
		local Canvas = Hud.Canvas
		if not Canvas then
			return
		end
		if not Fade.List then
			Fade.List = CollectFade(Canvas)
		end
		Fade.Target = Target
		if not Fade.Conn then
			Fade.Conn = RunService.Heartbeat:Connect(StepFade)
		end
	end

	function Hud.HookCanvas(Canvas)
		if Hud.Hooked == Canvas then
			return
		end
		Hud.Hooked = Canvas
		Fade.Open = Canvas.Visible
		Fade.Alpha = Canvas.Visible and 1 or 0
		Fade.Target = Fade.Alpha
		Canvas:GetPropertyChangedSignal("Visible"):Connect(function()
			if Fade.Internal or not Hud.Settings.Animate then
				return
			end
			if Canvas.Visible then
				-- opening: start fully transparent, then fade in
				Fade.Open = true
				Fade.Alpha = 0
				Fade.List = CollectFade(Canvas)
				Paint(0)
				RunFade(1)
			else
				-- the library hid it instantly: keep it up and fade out instead
				Fade.Open = false
				Fade.Internal = true
				Canvas.Visible = true
				Fade.Internal = false
				RunFade(0)
			end
		end)
	end

	function Hud.SetOpen(Open)
		local Canvas = Hud.GetCanvas()
		if not Canvas then
			return
		end
		if Open then
			if Canvas.Visible then
				if Fade.Target ~= 1 then
					Fade.Open = true
					RunFade(1)
				end
			else
				Canvas.Visible = true
			end
		elseif Canvas.Visible then
			Canvas.Visible = false
		end
	end

	function Hud.ToggleMenu()
		local Canvas = Hud.GetCanvas()
		local Want = true
		if Canvas then
			Hud.HookCanvas(Canvas)
			Want = not (Canvas.Visible and Fade.Target == 1)
		end
		if type(Femboy.ToggleMenu) == "function" then
			pcall(Femboy.ToggleMenu, Want)
		end
		Hud.SetOpen(Want)
		if not Want then
			pcall(function()
				if Femboy.OpenPopup and Femboy.OpenPopup.Close then
					Femboy.OpenPopup.Close()
				end
			end)
		end
	end

