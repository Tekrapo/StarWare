	function Hud.Start()
		local Gui = New("ScreenGui", {
			Name = "femboyHud",
			ResetOnSpawn = false,
			IgnoreGuiInset = true,
			DisplayOrder = 100,
			ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
		})
		if not Mount(Gui) then
			Warn("hud", "could not parent the HUD gui")
			return
		end
		Hud.Gui = Gui

		local Ok, Err = pcall(BuildWatermark, Gui)
		if not Ok then
			Warn("watermark", Err)
		end
		Ok, Err = pcall(BuildList, Gui)
		if not Ok then
			Warn("keybind list", Err)
		end
		Ok, Err = pcall(Hud.ApplyScale)
		if not Ok then
			Warn("scale", Err)
		end
		task.delay(0.15, function()
			pcall(Hud.ApplyScale)
		end)

		local Camera = workspace.CurrentCamera
		if Camera then
			Camera:GetPropertyChangedSignal("ViewportSize"):Connect(function()
				Hud.RequestScale()
			end)
		end

		-- own key tracking: the list does not depend on how the library reports key state
		UserInputService.InputBegan:Connect(function(Input)
			pcall(OnInput, Input, true)
		end)
		UserInputService.InputEnded:Connect(function(Input)
			pcall(OnInput, Input, false)
		end)

		task.spawn(function()
			local Tick = 0
			while Gui.Parent do
				Tick = Tick + 1
				local Done, Problem = pcall(Hud.Refresh)
				if not Done then
					Warn("keybind list refresh", Problem)
				end
				if Tick == 1 or Tick == 12 then
					Hud.KillLibraryHud(true)
				elseif Tick % 5 == 0 then
					Hud.KillLibraryHud(false)
				end
