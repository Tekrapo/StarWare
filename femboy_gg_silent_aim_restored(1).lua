-- Client-side bullet trail: listens for the local character's Shoot animation.
local TrailConnections = {}
local function DrawBulletTrail(Character)
    local Humanoid = Character:FindFirstChildOfClass("Humanoid")
    if not Humanoid then return end
    local Animator = Humanoid:FindFirstChildOfClass("Animator") or Humanoid
    local Connection = Animator.AnimationPlayed:Connect(function(Track)
        if not BulletTracerEnabled then return end
        local Animation = Track.Animation
        if Track.Name ~= "Shoot" and not (Animation and Animation.Name == "Shoot") then return end
        local Camera = workspace.CurrentCamera
        if not Camera then return end
        local Origin = Camera.CFrame.Position
        local Direction = Camera.CFrame.LookVector * 650
        local Params = RaycastParams.new()
        Params.FilterType = Enum.RaycastFilterType.Exclude
        Params.FilterDescendantsInstances = { Character }
        local Hit = workspace:Raycast(Origin, Direction, Params)
        local Finish = Hit and Hit.Position or (Origin + Direction)
        local Distance = (Finish - Origin).Magnitude
        if Distance < 2 then return end

        local A = Instance.new("Part")
        A.Name = "femboy_gg_tracer_a"
        A.Anchored = true; A.CanCollide = false; A.CanQuery = false; A.CanTouch = false
        A.Transparency = 1; A.Size = Vector3.new(0.05, 0.05, 0.05); A.CFrame = CFrame.new(Origin); A.Parent = workspace
        local B = Instance.new("Part")
        B.Name = "femboy_gg_tracer_b"
        B.Anchored = true; B.CanCollide = false; B.CanQuery = false; B.CanTouch = false
        B.Transparency = 1; B.Size = Vector3.new(0.05, 0.05, 0.05); B.CFrame = CFrame.new(Finish); B.Parent = workspace
        local At0 = Instance.new("Attachment", A)
        local At1 = Instance.new("Attachment", B)
        local Beam = Instance.new("Beam")
        Beam.Name = "femboy_gg_bullet_tracer"
        Beam.Attachment0 = At0; Beam.Attachment1 = At1
        Beam.FaceCamera = true; Beam.LightEmission = 1; Beam.LightInfluence = 0
        Beam.Color = ColorSequence.new(BulletTracerColor)
        if BulletTracerStyle == "Clean beam" then
            Beam.Width0 = 0.085; Beam.Width1 = 0.02
        else
            Beam.Width0 = 0.16; Beam.Width1 = 0.035
        end
        Beam.Transparency = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0.08), NumberSequenceKeypoint.new(1, 0.28) })
        Beam.Parent = A
        local Duration = BulletTracerDuration
        local Started = os.clock()
        local FadeConnection
        FadeConnection = RunService.RenderStepped:Connect(function()
            local Alpha = math.clamp((os.clock() - Started) / Duration, 0, 1)
            Beam.Transparency = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0.08 + Alpha * 0.92), NumberSequenceKeypoint.new(1, 0.28 + Alpha * 0.72) })
            local BaseWidth = BulletTracerStyle == "Clean beam" and 0.085 or 0.16
            local TipWidth = BulletTracerStyle == "Clean beam" and 0.02 or 0.035
            Beam.Width0 = BaseWidth * (1 - Alpha * 0.65)
            Beam.Width1 = TipWidth * (1 - Alpha * 0.65)
            if Alpha >= 1 then
                FadeConnection:Disconnect()
                A:Destroy(); B:Destroy()
            end
        end)
    end)
    table.insert(TrailConnections, Connection)
end
local LocalPlayer = game:GetService("Players").LocalPlayer
