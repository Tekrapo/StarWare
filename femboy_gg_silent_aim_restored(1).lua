	local function PollLinks()
		for Key, Link in pairs(Hud.Links) do
			local Obj = Link.Obj
			if Link.Kind == "toggle" then
				if type(Obj) == "table" and type(Obj.State) == "boolean" and Obj.State ~= Link.Last then
					Link.Last = Obj.State
					Link.Apply(Obj.State)
				end
			elseif Link.Kind == "slider" then
				if type(Obj) == "table" and type(Obj.Value) == "number" and Obj.Value ~= Link.Last then
					Link.Last = Obj.Value
					Link.Apply(Obj.Value)
				end
			end
		end
	end

	function Hud.Refresh()
		pcall(PollLinks)

		local Panel = Hud.List
		if not Panel then
			return
		end

		local Shown = {}
		local Count = 0
		for Index, Entry in ipairs(Hud.Binds) do
			local Key = BoundKey(Entry)
			local On = FeatureOn(Entry)
			local Live = Engaged(Entry)
			local Visible = Key ~= nil and ((On == true) or (On == nil and Live))
			if Visible then
				Count = Count + 1
				local Mode = BoundMode(Entry) or "Toggle"
				local Id = tostring(Index)
				Shown[Id] = true

				local Row = Hud.Rows[Id]
				if not Row then
					local Frame = New("Frame", {
						LayoutOrder = Index,
						Size = UDim2.new(1, 0, 0, 24),
						BackgroundTransparency = 1,
						ZIndex = 51,
					}, Panel)
					local function Cell(Name, Pos, Size, Align)
						return New("TextLabel", {
							Name = Name,
							Position = Pos,
							Size = Size,
							BackgroundTransparency = 1,
							Font = Enum.Font.GothamMedium,
							TextSize = 13,
							TextXAlignment = Align,
							TextTruncate = Enum.TextTruncate.AtEnd,
							ZIndex = 52,
						}, Frame)
					end
					Row = {
						Frame = Frame,
						Name = Cell("Name", UDim2.fromOffset(0, 0), UDim2.new(0.5, 0, 1, 0), Enum.TextXAlignment.Left),
						Key = Cell("Key", UDim2.fromScale(0.5, 0), UDim2.new(0.25, 0, 1, 0), Enum.TextXAlignment.Center),
						Mode = Cell("Mode", UDim2.fromScale(0.75, 0), UDim2.new(0.25, 0, 1, 0), Enum.TextXAlignment.Right),
					}
					Hud.Rows[Id] = Row
				end
				local Accent = ThemeColor("Accent", Color3.fromRGB(120, 140, 255))
				Row.Name.Text = Entry.Name
				Row.Key.Text = KeyText(Key)
				Row.Mode.Text = tostring(Mode)
				Row.Name.TextColor3 = Live and Color3.fromRGB(240, 241, 245) or Color3.fromRGB(150, 154, 170)
				Row.Key.TextColor3 = Live and Accent or Color3.fromRGB(110, 114, 130)
				Row.Mode.TextColor3 = Color3.fromRGB(150, 154, 170)
			end
		end

		for Id, Row in pairs(Hud.Rows) do
			if not Shown[Id] then
				Row.Frame:Destroy()
				Hud.Rows[Id] = nil
			end
		end

		Panel.Visible = Hud.Settings.KeybindList == true and Count > 0
	end

	-- ---------- remove the library's own watermark / keybind list ----------
	local function LooksLikeStats(Root)
		for _, Obj in ipairs(Root:GetDescendants()) do
			if Obj:IsA("TextLabel") then
				local Text = string.lower(Obj.Text)
				if Text:find("fps", 1, true) or Text:find("%d+%s*ms") then
					return true
				end
			end
		end
		return false
	end

	local function KillByTable()
		local Killed = 0
		for _, Name in ipairs({ "Watermark", "KeybindList" }) do
			local Tab = Femboy[Name]
			if type(Tab) == "table" then
				for _, Field in ipairs({ "Frame", "Container", "Holder", "Root" }) do
					local Obj = Tab[Field]
					if typeof(Obj) == "Instance" and not (Hud.Gui and Obj:IsDescendantOf(Hud.Gui)) then
						pcall(function()
							Obj.Visible = false
							Obj:Destroy()
						end)
						Killed = Killed + 1
					end
				end
			end
		end
		return Killed
	end

	-- time-sliced so it never causes a frame hitch
	local function KillByScan()
		local Killed = 0
		local Canvas = Hud.GetCanvas()
		local Roots = {}
		if gethui then
			pcall(function()
				table.insert(Roots, gethui())
			end)
		end
		table.insert(Roots, CoreGui)
		pcall(function()
			table.insert(Roots, Players.LocalPlayer:FindFirstChild("PlayerGui"))
		end)

		local Budget = 0
		for _, Root in ipairs(Roots) do
			for _, Gui in ipairs(Root:GetChildren()) do
				if Gui:IsA("ScreenGui") and Gui ~= Hud.Gui then
					local Found = {}
					for _, Obj in ipairs(Gui:GetDescendants()) do
						Budget = Budget + 1
						if Budget % 400 == 0 then
							task.wait()
						end
						if Obj:IsA("TextLabel") and string.lower(Obj.Text):match("^%s*femboy") then
							table.insert(Found, Obj)
						end
					end
					for _, Label in ipairs(Found) do
						local Target, Cur = Label, Label.Parent
						while Cur and Cur ~= Gui and Cur:IsA("GuiObject") and Cur.AbsoluteSize.Y <= 80 and Cur.AbsoluteSize.X <= 700 do
							Target, Cur = Cur, Cur.Parent
						end
						local IsWindow = Canvas and (Target == Canvas or Target:IsDescendantOf(Canvas) or Canvas:IsDescendantOf(Target))
						if Target ~= Label and Target.Parent and not IsWindow and LooksLikeStats(Target) then
							pcall(function()
								Target.Visible = false
								Target:Destroy()
							end)
							Killed = Killed + 1
						end
					end
				end
			end
		end
		return Killed
	end

	function Hud.KillLibraryHud(Wide)
		local Killed = 0
		local Ok, Result = pcall(KillByTable)
		if Ok then
			Killed = Killed + Result
		end
		if Wide then
			task.spawn(function()
				local Ok2, Result2 = pcall(KillByScan)
				if not Ok2 then
					Warn("watermark scan", Result2)
				end
			end)
		end
		return Killed
	end

	-- the library must not draw its own watermark / keybind list any more
	for _, Name in ipairs({ "SetWatermark", "SetKeybindList" }) do
		if type(Femboy[Name]) == "function" then
			Hud["Orig" .. Name] = Femboy[Name]
			Femboy[Name] = function() end
		end
	end

	-- ---------- public api ----------
	function Hud.Bind(Label, Props)
		local Entry = {
			Label = Label,
			Name = tostring(Label.Text or "Keybind"),
			Mode = Props.Type or "Toggle",
			Key0 = Props.Key,
			Tracked = false,
			Own = false,
		}
		local Original = Props.Callback
		Props.Callback = function(State, ...)
			Entry.CbSeen = true
			if type(State) == "boolean" then
				Entry.Tracked = State
			else
				Entry.Tracked = not Entry.Tracked
			end
			if Original then
				return Original(State, ...)
			end
		end
		local Obj = Label:Keybind(Props)
		Entry.Obj = Obj
		table.insert(Hud.Binds, Entry)
		return Obj
	end

	function Hud.Tog(Label, Props)
		local Rec = { Tracked = Props.State == true }
		local Original = Props.Callback
		Props.Callback = function(State, ...)
			Flip(Rec, State)
			if Original then
				return Original(State, ...)
			end
		end
		Rec.Obj = Label:Toggle(Props)
		Hud.Toggles[Label] = Rec
		return Rec.Obj
	end

	-- settings controls: callback + polling, so they work whatever the library passes to callbacks
	function Hud.SettingToggle(Section, Text, Key, Default, Apply)
		local Label = Section:Label({ Text = Text })
		local Rec = { Tracked = Default }
		local Link = { Kind = "toggle", Last = Default, Apply = Apply }
		Link.Obj = Label:Toggle({
			State = Default,
			Flag = "Hud" .. Key,
			Callback = function(State)
				local Value = Flip(Rec, State)
				if Value ~= Link.Last then
					Link.Last = Value
					Apply(Value)
				end
			end,
		})
		Hud.Links[Key] = Link
		return Link.Obj
	end

	function Hud.SettingSlider(Section, Props, Key, Apply)
		local Link = { Kind = "slider", Last = Props.Value, Apply = Apply }
		Props.Flag = "Hud" .. Key
		Props.Callback = function(Value)
			if type(Value) == "number" and Value ~= Link.Last then
				Link.Last = Value
				Apply(Value)
			end
		end
		Link.Obj = Section:Slider(Props)
		Hud.Links[Key] = Link
		return Link.Obj
	end

