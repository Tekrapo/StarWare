	-- ---------- keybind list ----------
	local KeyNames = {
		MouseButton1 = "MB1", MouseButton2 = "MB2", MouseButton3 = "MB3",
		LeftShift = "LShift", RightShift = "RShift", LeftControl = "LCtrl", RightControl = "RCtrl",
		LeftAlt = "LAlt", RightAlt = "RAlt", Backspace = "Back", Return = "Enter",
	}

	local function KeyName(Key)
		if typeof(Key) == "EnumItem" then
			return Key.Name
		end
		if type(Key) == "string" then
			return Key
		end
		return nil
	end

	local function ValidKey(Key)
		local Name = KeyName(Key)
		return Name ~= nil and Name ~= "" and Name ~= "Unknown" and Name ~= "None"
	end

	local function KeyText(Key)
		local Name = KeyName(Key)
		if not Name then
			return "-"
		end
		return KeyNames[Name] or Name
	end

	-- the key currently bound, tolerant of libraries that expose it differently
	local function BoundKey(Entry)
		local Obj = Entry.Obj
		if type(Obj) == "table" then
			local Key = Obj.Key
			if ValidKey(Key) then
				Entry.KeySeen = true
				return Key
			end
			if Entry.KeySeen then
				return nil -- it was bound before and has been cleared
			end
		end
		return Entry.Key0
	end

	local function BoundMode(Entry)
		local Obj = Entry.Obj
		if type(Obj) == "table" and type(Obj.Type) == "string" then
			return Obj.Type
		end
		return Entry.Mode
	end

	local function FeatureOn(Entry)
		local Tog = Hud.Toggles[Entry.Label]
		if not Tog then
			return nil -- no toggle on this row
		end
		return ToggleState(Tog.Obj, Tog)
	end

	local function Engaged(Entry)
		if BoundMode(Entry) == "Always" then
			return true
		end
		if Entry.CbSeen then
			return Entry.Tracked == true
		end
		return Entry.Own == true
	end

	local function KeyMatches(Key, Input)
		if typeof(Key) == "EnumItem" then
			return Input.KeyCode == Key or Input.UserInputType == Key
		end
		if type(Key) == "string" then
			return Input.KeyCode.Name == Key or Input.UserInputType.Name == Key
		end
		return false
	end

	local function OnInput(Input, Began)
		if UserInputService:GetFocusedTextBox() then
			return
		end
		for _, Entry in ipairs(Hud.Binds) do
			local Key = BoundKey(Entry)
			if Key and KeyMatches(Key, Input) then
				local Mode = BoundMode(Entry)
				if Mode == "Hold" then
					Entry.Own = Began
				elseif Mode == "Toggle" and Began then
					Entry.Own = not Entry.Own
				end
			end
		end
	end

