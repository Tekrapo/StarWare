		local Parents = {}
		if gethui then
			table.insert(Parents, function()
				return gethui()
			end)
		end
		table.insert(Parents, function()
			return CoreGui
		end)
		table.insert(Parents, function()
			return Players.LocalPlayer:WaitForChild("PlayerGui", 5)
		end)
		for _, Get in ipairs(Parents) do
