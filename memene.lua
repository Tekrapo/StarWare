	local function KeyText(Key)
		if typeof(Key) ~= "EnumItem" then
			return "-"
		end
		return KeyNames[Key.Name] or Key.Name
	end

	local function HasKey(Obj)
		if type(Obj) ~= "table" then
			return true
		end
		local Key = Obj.Key
		if Key == nil then
			return false
		end
		if typeof(Key) == "EnumItem" and (Key.Name == "Unknown" or Key.Name == "None") then
			return false
		end
		return true
	end

	local function FeatureOn(Entry)
		local Tog = Hud.Toggles[Entry.Label]
		if not Tog then
			return true
		end
		if type(Tog.Obj) == "table" and type(Tog.Obj.State) == "boolean" then
			return Tog.Obj.State
		end
		return Tog.Tracked == true
	end

	local function IsActive(Entry)
		local Obj = Entry.Obj
		if not HasKey(Obj) or not FeatureOn(Entry) then
			return false
		end
		if type(Obj) == "table" and type(Obj.State) == "boolean" then
			return Obj.State
		end
		return Entry.Tracked == true
	end

