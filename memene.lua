	function Hud.Refresh()
		local Panel = Hud.List
		if not Panel then
			return
		end

		local ActiveNow = {}
		local Count = 0
		for Index, Entry in ipairs(Hud.Binds) do
			if IsActive(Entry) then
				Count = Count + 1
				local Obj = Entry.Obj
				local Mode = (type(Obj) == "table" and Obj.Type) or Entry.Mode or "Toggle"
				local Key = KeyText(type(Obj) == "table" and Obj.Key or nil)
				local Id = tostring(Index)
				ActiveNow[Id] = true

				local Row = Hud.Rows[Id]
				if not Row then
					local Frame = New("Frame", {
						LayoutOrder = Index,
						Size = UDim2.new(1, 0, 0, 22),
						BackgroundTransparency = 1,
						ZIndex = 51,
					}, Panel)
					local function Cell(Name, Pos, Size, Align, Color)
						return New("TextLabel", {
							Name = Name,
							Position = Pos,
							Size = Size,
							BackgroundTransparency = 1,
							Font = Enum.Font.GothamMedium,
							TextSize = 12,
							TextColor3 = Color,
							TextXAlignment = Align,
							TextTruncate = Enum.TextTruncate.AtEnd,
							ZIndex = 52,
						}, Frame)
					end
					local Accent = ThemeColor("Accent", Color3.fromRGB(120, 140, 255))
					Row = {
						Frame = Frame,
						Name = Cell("Name", UDim2.fromOffset(0, 0), UDim2.new(0.5, 0, 1, 0), Enum.TextXAlignment.Left, Color3.fromRGB(235, 236, 240)),
						Key = Cell("Key", UDim2.fromScale(0.5, 0), UDim2.new(0.25, 0, 1, 0), Enum.TextXAlignment.Center, Accent),
						Mode = Cell("Mode", UDim2.fromScale(0.75, 0), UDim2.new(0.25, 0, 1, 0), Enum.TextXAlignment.Right, Color3.fromRGB(150, 154, 170)),
					}
					Hud.Rows[Id] = Row
				end
				Row.Name.Text = Entry.Name
				Row.Key.Text = Key
				Row.Mode.Text = tostring(Mode)
			end
		end

		for Id, Row in pairs(Hud.Rows) do
			if not ActiveNow[Id] then
				Row.Frame:Destroy()
				Hud.Rows[Id] = nil
			end
		end

		Panel.Visible = Hud.Settings.KeybindList == true and Count > 0
	end

	-- ---------- remove the library's own watermark / keybind list ----------
	local function LooksLikeStats(Root)
		for _, Obj in ipairs(Root:GetDescendants()) do
			if Obj:IsA("TextLabel") then
				local Text = string.lower(Obj.Text)
				if Text:find("fps", 1, true) or Text:find("%d+%s*ms") then
					return true
				end
			end
		end
		return false
	end

	local function KillByTable()
		local Killed = 0
		for _, Name in ipairs({ "Watermark", "KeybindList" }) do
			local Tab = Femboy[Name]
			if type(Tab) == "table" then
				for _, Field in ipairs({ "Frame", "Container", "Holder", "Root" }) do
					local Obj = Tab[Field]
					if typeof(Obj) == "Instance" and not (Hud.Gui and Obj:IsDescendantOf(Hud.Gui)) then
						pcall(function()
							Obj.Visible = false
							Obj:Destroy()
						end)
						Killed = Killed + 1
					end
				end
			end
		end
		return Killed
	end

	local function KillByScan()
		local Killed = 0
		local Canvas = FindWindow()
		local Roots = {}
		if gethui then
			pcall(function()
				table.insert(Roots, gethui())
			end)
		end
		table.insert(Roots, CoreGui)
		pcall(function()
			table.insert(Roots, Players.LocalPlayer:FindFirstChild("PlayerGui"))
		end)

		for _, Root in ipairs(Roots) do
			for _, Gui in ipairs(Root:GetChildren()) do
				if Gui:IsA("ScreenGui") and Gui ~= Hud.Gui then
					local Found = {}
					for _, Obj in ipairs(Gui:GetDescendants()) do
						if Obj:IsA("TextLabel") and string.lower(Obj.Text):match("^%s*femboy") then
							table.insert(Found, Obj)
						end
					end
					for _, Label in ipairs(Found) do
						-- climb to the outermost small container around the title label
						local Target, Cur = Label, Label.Parent
						while Cur and Cur ~= Gui and Cur:IsA("GuiObject") and Cur.AbsoluteSize.Y <= 80 and Cur.AbsoluteSize.X <= 700 do
							Target, Cur = Cur, Cur.Parent
						end
						local IsWindow = Canvas and (Target == Canvas or Target:IsDescendantOf(Canvas) or Canvas:IsDescendantOf(Target))
						if Target ~= Label and Target.Parent and not IsWindow and LooksLikeStats(Target) then
							pcall(function()
								Target.Visible = false
								Target:Destroy()
							end)
							Killed = Killed + 1
						end
					end
				end
			end
		end
		return Killed
	end

	function Hud.KillLibraryHud(Wide)
		local Killed = 0
		local Ok, Result = pcall(KillByTable)
		if Ok then
			Killed = Killed + Result
		end
		if Wide then
			local Ok2, Result2 = pcall(KillByScan)
			if Ok2 then
				Killed = Killed + Result2
			else
				Warn("watermark scan", Result2)
			end
		end
		return Killed
	end

	-- the library must not draw its own watermark / keybind list any more
	for _, Name in ipairs({ "SetWatermark", "SetKeybindList" }) do
		if type(Femboy[Name]) == "function" then
			Hud["Orig" .. Name] = Femboy[Name]
			Femboy[Name] = function() end
		end
	end

	-- ---------- public api ----------
	function Hud.Bind(Label, Props)
		local Entry = {
			Label = Label,
			Name = tostring(Label.Text or "Keybind"),
			Mode = Props.Type or "Toggle",
			Tracked = false,
		}
		local Original = Props.Callback
		Props.Callback = function(State, ...)
			Entry.Tracked = State == true
			if Original then
				return Original(State, ...)
			end
		end
		local Obj = Label:Keybind(Props)
		Entry.Obj = Obj
		table.insert(Hud.Binds, Entry)
		return Obj
	end

	function Hud.Tog(Label, Props)
		local Rec = { Tracked = Props.State == true }
		local Original = Props.Callback
		Props.Callback = function(State, ...)
			if type(State) == "boolean" then
				Rec.Tracked = State
			end
			if Original then
				return Original(State, ...)
			end
		end
		Rec.Obj = Label:Toggle(Props)
		Hud.Toggles[Label] = Rec
		return Rec.Obj
	end

	function Hud.SetWatermark(State)
		Hud.Settings.Watermark = State == true
		if Hud.Watermark then
			Hud.Watermark.Visible = Hud.Settings.Watermark
		end
	end

	function Hud.SetKeybindList(State)
		Hud.Settings.KeybindList = State == true
		pcall(Hud.Refresh)
	end

	function Hud.SetAutoScale(State)
		Hud.Settings.AutoScale = State == true
		pcall(Hud.ApplyScale)
	end

	function Hud.SetScale(Percent)
		if type(Percent) == "number" then
			Hud.Settings.Scale = Percent / 100
			pcall(Hud.ApplyScale)
		end
	end

	function Hud.Start()
		local Gui = New("ScreenGui", {
			Name = "femboyHud",
			ResetOnSpawn = false,
			IgnoreGuiInset = true,
			DisplayOrder = 100,
			ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
		})
		if not Mount(Gui) then
			Warn("hud", "could not parent the HUD gui")
			return
		end
		Hud.Gui = Gui

		local Ok, Err = pcall(BuildWatermark, Gui)
		if not Ok then
			Warn("watermark", Err)
		end
		Ok, Err = pcall(BuildList, Gui)
		if not Ok then
			Warn("keybind list", Err)
		end
		Ok, Err = pcall(Hud.ApplyScale)
		if not Ok then
			Warn("scale", Err)
		end
		task.delay(0.15, function()
			pcall(Hud.ApplyScale)
		end)

		local Camera = workspace.CurrentCamera
		if Camera then
			Camera:GetPropertyChangedSignal("ViewportSize"):Connect(function()
				pcall(Hud.ApplyScale)
			end)
		end

		task.spawn(function()
			local Tick = 0
			while Gui.Parent do
				Tick = Tick + 1
				local Done, Problem = pcall(Hud.Refresh)
				if not Done then
					Warn("keybind list refresh", Problem)
				end
				if Tick == 1 or Tick == 5 or Tick == 15 or Tick == 40 or Tick == 100 then
					Hud.KillLibraryHud(true)
				elseif Tick % 5 == 0 then
					Hud.KillLibraryHud(false)
				end
				task.wait(0.2)
			end
			if Hud.StatsConn then
				Hud.StatsConn:Disconnect()
			end
		end)
	end
end
